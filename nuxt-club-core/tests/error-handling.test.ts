import { describe, it, expect } from 'vitest'
import { createClubError } from '../server/utils/errors'
import { parseClubError } from '../app/composables/useClubError'

describe('Error Handling (createClubError & parseClubError)', () => {
  describe('createClubError', () => {
    it('creates H3Error with structured ClubErrorResponse in data', () => {
      const error = createClubError({
        statusCode: 401,
        code: 'UNAUTHORIZED',
        message: 'Pro přístup k této akci musíte být přihlášeni.'
      })

      expect(error.statusCode).toBe(401)
      expect(error.statusMessage).toBe('Pro přístup k této akci musíte být přihlášeni.')
      expect(error.message).toBe('Pro přístup k této akci musíte být přihlášeni.')
      expect(error.data).toEqual({
        statusCode: 401,
        code: 'UNAUTHORIZED',
        message: 'Pro přístup k této akci musíte být přihlášeni.'
      })
    })

    it('attaches fieldErrors when provided (e.g. validation errors)', () => {
      const fieldErrors = {
        email: ['Zadejte platnou e-mailovou adresu'],
        password: ['Heslo je příliš krátké']
      }

      const error = createClubError({
        statusCode: 400,
        code: 'VALIDATION_ERROR',
        message: 'Neplatná vstupní data',
        fieldErrors
      })

      expect(error.statusCode).toBe(400)
      expect(error.data).toEqual({
        statusCode: 400,
        code: 'VALIDATION_ERROR',
        message: 'Neplatná vstupní data',
        fieldErrors
      })
    })
  })

  describe('parseClubError', () => {
    it('parses error generated by createClubError', () => {
      const createdError = createClubError({
        statusCode: 403,
        code: 'FORBIDDEN',
        message: 'Nedostatečná oprávnění.',
        fieldErrors: {
          role: ['Role admin je vyžadována']
        }
      })

      const parsed = parseClubError(createdError)
      expect(parsed.code).toBe('FORBIDDEN')
      expect(parsed.message).toBe('Nedostatečná oprávnění.')
      expect(parsed.fieldErrors).toEqual({
        role: 'Role admin je vyžadována'
      })
    })

    it('parses FetchError structure with data payload', () => {
      const mockFetchError = {
        data: {
          statusCode: 400,
          code: 'VALIDATION_ERROR',
          message: 'Chyba formuláře',
          fieldErrors: {
            email: ['E-mail již existuje', 'Neplatný formát'],
            name: 'Jméno je povinné'
          }
        }
      }

      const parsed = parseClubError(mockFetchError)
      expect(parsed.code).toBe('VALIDATION_ERROR')
      expect(parsed.message).toBe('Chyba formuláře')
      // Should pick first message for email
      expect(parsed.fieldErrors.email).toBe('E-mail již existuje')
      expect(parsed.fieldErrors.name).toBe('Jméno je povinné')
    })

    it('parses fallback nested errors array format', () => {
      const nestedError = {
        data: {
          data: {
            errors: [
              { field: 'email', message: 'E-mail je neplatný' },
              { field: 'password', message: 'Heslo je příliš krátké' }
            ]
          }
        }
      }

      const parsed = parseClubError(nestedError)
      expect(parsed.fieldErrors).toEqual({
        email: 'E-mail je neplatný',
        password: 'Heslo je příliš krátké'
      })
    })

    it('returns default fallback when error is undefined or null', () => {
      const parsedNull = parseClubError(null)
      expect(parsedNull.message).toBe('Došlo k neočekávané chybě.')
      expect(parsedNull.fieldErrors).toEqual({})

      const parsedUndefined = parseClubError(undefined)
      expect(parsedUndefined.message).toBe('Došlo k neočekávané chybě.')
      expect(parsedUndefined.fieldErrors).toEqual({})
    })

    it('falls back to errObj.message or errObj.statusMessage when data is not present', () => {
      const standardError = new Error('Běžná JS chyba')
      const parsed = parseClubError(standardError)
      expect(parsed.message).toBe('Běžná JS chyba')
      expect(parsed.fieldErrors).toEqual({})

      const statusMessageError = { statusMessage: 'Chyba serveru' }
      const parsedStatus = parseClubError(statusMessageError)
      expect(parsedStatus.message).toBe('Chyba serveru')
    })
  })
})
